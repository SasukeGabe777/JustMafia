'use strict';
// Chooses one candidate per soundtrack cue, copies it into public/audio/music/ and writes
// public/audio/music/manifest.json (with each file's loop points). See docs/music.md.
//
//   node tools/music/pick.js <candidates dir> [--listen <dir>] [--use <id>=<seed>,...] [--max-mb N]
//
// <candidates dir> holds process.py's output: <id with / as __>__s<seed>.{ogg,mp3,json}.
// The best-scoring candidate wins unless tools/music/picks.json (or --use) names a seed.
// --listen copies every candidate's mp3 into a listening folder (chosen ones marked).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'public', 'audio', 'music');
const PICKS = path.join(__dirname, 'picks.json');
const args = process.argv.slice(2);
const dir = args[0];
const opt = (k) => { const i = args.indexOf(k); return i > 0 ? args[i + 1] : null; };
if (!dir || !fs.existsSync(dir)) { console.error('usage: node tools/music/pick.js <candidates dir> [--listen dir] [--use id=seed,...]'); process.exit(1); }

// Which shared mood set each box game uses (games not listed use _default = party).
const SETS = {
  party: ['generic', 'price', 'trivia', 'emoji', 'memes', 'letters', 'plinko', 'snap', 'tune', 'bid', 'likely', 'debate'],
  jazz: ['blackjack', 'escape', 'truths', 'undercover', 'funny', 'blanks', 'whosaid', 'bomb'],
  spooky: ['zombie', 'alien'],
  epic: ['kingdoms', 'summon', 'president'],
  acoustic: ['ducks', 'spectrum', 'marble', 'sketch', 'colormatch', 'actout', 'pizza', 'quickdraw'],
};
// Game-specific cues that can borrow a standard cue's track (a cue with no track plays the synth score).
const ALIASES = { story: 'think', action: 'play', speech: 'think', alarm: 'tense', standoff: 'tense', race: 'play', kitchen: 'play' };
// JustMafia: worlds whose other moments use the noir tone set (the rest use the shared moods).
const TONES = { noir: ['noir'] };

const picks = fs.existsSync(PICKS) ? JSON.parse(fs.readFileSync(PICKS, 'utf8')) : {};
for (const u of (opt('--use') || '').split(',').filter(Boolean)) { const [id, seed] = u.split('='); picks[id] = Number(String(seed).replace(/^s/, '')); }

const cands = {};
for (const f of fs.readdirSync(dir)) {
  if (!f.endsWith('.json')) continue;
  const m = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  if (!m.id || !fs.existsSync(path.join(dir, f.replace(/\.json$/, '.ogg')))) continue;
  (cands[m.id] = cands[m.id] || []).push({ ...m, base: f.replace(/\.json$/, '') });
}
const chosen = {};
for (const [id, list] of Object.entries(cands)) {
  list.sort((a, b) => b.score - a.score);
  const want = picks[id] != null ? list.find((c) => c.seed === picks[id]) : null;
  chosen[id] = want || list[0];
}

// Copy the chosen files and build the manifest.
const manifest = {
  _doc: 'Generated by tools/music/pick.js (docs/music.md). games.<scoreKey>.<cue> or sets.<set>.<cue> -> file under /audio/music/ with loop points (seconds). mafia: worlds.<world>.<mood> -> tones.<tone>.<mood> -> moods.<mood>. AI-generated music (ACE-Step 1.5, MIT).',
  aliases: ALIASES,
  sets: {},
  games: { _default: { set: 'party' }, menu: { set: null }, party: { set: null } },
  mafia: { moods: {}, tones: {}, worlds: {} },
};
for (const [set, games] of Object.entries(SETS)) for (const g of games) manifest.games[g] = { set };
for (const [tone, worlds] of Object.entries(TONES)) for (const w of worlds) manifest.mafia.worlds[w] = { tone };
const keep = new Set();
let bytes = 0;
for (const [id, c] of Object.entries(chosen).sort()) {
  const rel = id + '.ogg', dest = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(path.join(dir, c.base + '.ogg'), dest);
  keep.add(path.normalize(dest)); bytes += fs.statSync(dest).size;
  const e = { file: rel, loopStart: c.loopStart, loopEnd: c.loopEnd };
  const p = id.split('/');
  if (p[0] === 'menu') manifest.games.menu[p[1]] = e;
  else if (id === 'box/lobby') { (manifest.sets.party = manifest.sets.party || {}).lobby = e; manifest.games.menu.lobby = e; }
  else if (p[0] === 'sets') (manifest.sets[p[1]] = manifest.sets[p[1]] || {})[p[2]] = e;
  else if (p[0] === 'party') manifest.games.party[p[1]] = e;
  else if (p[0] === 'games') (manifest.games[p[1]] = manifest.games[p[1]] || {})[p[2]] = e;
  else if (p[0] === 'mafia' && p[1] === 'moods') manifest.mafia.moods[p[2]] = e;
  else if (p[0] === 'mafia' && p[1] === 'worlds') (manifest.mafia.worlds[p[2]] = manifest.mafia.worlds[p[2]] || {})[p[3]] = e;
  else if (p[0] === 'mafia') ((manifest.mafia.tones[p[1]] = manifest.mafia.tones[p[1]] || {}))[p[2]] = e;
  else console.warn('unplaced cue', id);
}
// The lobby track doubles as every other set's lobby where a set has none.
for (const s of Object.values(manifest.sets)) if (!s.lobby && manifest.sets.party && manifest.sets.party.lobby) s.lobby = manifest.sets.party.lobby;
fs.writeFileSync(path.join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 1) + '\n');
// Remove stale .ogg files no cue uses any more.
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((x) => (x.isDirectory() ? walk(path.join(d, x.name)) : [path.join(d, x.name)]));
for (const f of walk(OUT)) if (f.endsWith('.ogg') && !keep.has(path.normalize(f))) fs.unlinkSync(f);
fs.writeFileSync(PICKS, JSON.stringify(Object.fromEntries(Object.entries(chosen).sort().map(([id, c]) => [id, c.seed])), null, 1) + '\n');

// The listening folder: every candidate as mp3, the chosen one marked.
const listen = opt('--listen');
if (listen) {
  fs.mkdirSync(listen, { recursive: true });
  const lines = ['JustGameBox soundtrack candidates (AI-generated with ACE-Step 1.5).', 'CHOSEN = in the game now. To use another candidate run, in the repo:', '  node tools/music/pick.js "' + path.resolve(dir) + '" --use <cue id>=<seed>', '', 'cue id | seed | chosen | loop (s) | LUFS | vocal dB | flags | file'];
  for (const [id, list] of Object.entries(cands).sort()) for (const c of list) {
    const isC = chosen[id] === c, name = id.replace(/\//g, '__') + '__s' + c.seed + (isC ? '__CHOSEN' : '') + '.mp3';
    for (const old of fs.readdirSync(listen)) if (old.startsWith(id.replace(/\//g, '__') + '__s' + c.seed + '_') || old === id.replace(/\//g, '__') + '__s' + c.seed + '.mp3') fs.unlinkSync(path.join(listen, old));
    fs.copyFileSync(path.join(dir, c.base + '.mp3'), path.join(listen, name));
    lines.push([id, c.seed, isC ? 'CHOSEN' : '', c.loopStart + '-' + c.loopEnd, c.lufs, c.vocalDb, (c.flags || []).join(' '), name].join(' | '));
  }
  fs.writeFileSync(path.join(listen, 'README.txt'), lines.join('\r\n') + '\r\n');
}
console.log(Object.keys(chosen).length + ' cues, ' + (bytes / 1048576).toFixed(1) + ' MB in public/audio/music');
for (const [id, c] of Object.entries(chosen).sort()) console.log(' ', id.padEnd(34), 's' + c.seed, 'score', c.score, (c.flags || []).join(' '));
