'use strict';
// Regenerate THIRD_PARTY_NOTICES.md (repo root) from the installed packages and the vendored
// fonts:  node tools/third-party-notices.js   (after npm ci here and in desktop/)
// Re-run it whenever a dependency, font or other third-party asset is added or updated.
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const DESKTOP = path.join(ROOT, 'desktop');

function prodTree(dir) {
  const json = JSON.parse(execSync('npm ls --omit=dev --all --json', { cwd: dir, encoding: 'utf8', maxBuffer: 64e6, stdio: ['ignore', 'pipe', 'ignore'] }));
  const seen = new Map();
  (function walk(d) {
    for (const [name, v] of Object.entries(d.dependencies || {})) {
      if (!v.version) continue;
      const key = `${name}@${v.version}`;
      if (!seen.has(key)) {
        let pkg = {};
        try { pkg = JSON.parse(fs.readFileSync(path.join(dir, 'node_modules', name, 'package.json'), 'utf8')); } catch { /* nested copy */ }
        const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository && pkg.repository.url;
        seen.set(key, { name, version: v.version, license: typeof pkg.license === 'string' ? pkg.license : (pkg.license && pkg.license.type) || 'see package', repo: (repo || pkg.homepage || '').replace(/^git\+/, '').replace(/\.git$/, '') });
      }
      walk(v);
    }
  })(json);
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}
const table = (rows) => ['| Package | Version | Licence | Source |', '|---|---|---|---|', ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repo || ''} |`)].join('\n');

const server = prodTree(ROOT);
let desktop = [];
try { desktop = prodTree(DESKTOP); } catch { console.warn('desktop/ dependencies not installed; run npm ci in desktop/ first for the full list'); }
let electronVersion = '';
try { electronVersion = JSON.parse(fs.readFileSync(path.join(DESKTOP, 'package.json'), 'utf8')).devDependencies.electron; } catch { /* no desktop */ }
const fontsReadme = fs.readFileSync(path.join(ROOT, 'public', 'fonts', 'licenses', 'README.txt'), 'utf8').trim().split('\n').slice(2);

